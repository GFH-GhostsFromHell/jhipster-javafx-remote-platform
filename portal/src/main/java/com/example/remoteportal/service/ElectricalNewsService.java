package com.example.remoteportal.service;

import org.apache.pdfbox.Loader;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.text.PDFTextStripper;
import org.jsoup.Jsoup;
import org.jsoup.nodes.Document;
import org.jsoup.nodes.Element;
import org.jsoup.select.Elements;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;
import java.time.Instant;
import java.time.LocalDate;
import java.time.YearMonth;
import java.time.format.DateTimeFormatter;
import java.time.format.DateTimeParseException;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

@Service
public class ElectricalNewsService {
    private static final String ESA_BULLETINS = "https://esasafe.com/electrical-products/bulletins/";
    private static final List<String> ESA_NEWSROOMS = List.of(
        "https://esasafe.com/newsroom-2026/",
        "https://esasafe.com/newsroom-2025/",
        "https://esasafe.com/newsroom-2024/"
    );
    private static final Duration HTTP_TIMEOUT = Duration.ofSeconds(25);
    private static final Duration STALE_AFTER = Duration.ofMinutes(35);
    private static final DateTimeFormatter ESA_DATE = DateTimeFormatter.ofPattern("dd MMMM uuuu", Locale.ENGLISH);
    private static final DateTimeFormatter MONTH_YEAR = DateTimeFormatter.ofPattern("MMMM uuuu", Locale.ENGLISH);
    private static final Pattern ISSUE_DATE = Pattern.compile("(?im)\\bIssued\\s+([A-Z][a-z]+\\s+20\\d{2})\\b");
    private static final Pattern BULLETIN_NO = Pattern.compile("(?im)\\bBulletin\\s+([0-9]+-[0-9]+-[0-9]+)\\b");
    private static final Pattern RULES = Pattern.compile("(?im)^Rules?\\s+([^\\r\\n]{1,90})$");

    private final HttpClient http = HttpClient.newBuilder()
        .connectTimeout(Duration.ofSeconds(12))
        .followRedirects(HttpClient.Redirect.NORMAL)
        .build();
    private final Map<String, BulletinMeta> bulletinMetaCache = new ConcurrentHashMap<>();
    private volatile Snapshot snapshot = new Snapshot(
        Instant.EPOCH,
        List.of(),
        List.of("ESA public OESC bulletins", "ESA OESC/CEC code announcements"),
        "Waiting for first poll",
        "Severity is generated by Electrical Workbench and is not an official ESA/CSA severity rating. Full 2024 OESC bulletins may require the purchased OESC/CSA OnDemand access."
    );

    public Snapshot current() {
        Snapshot current = snapshot;
        if (current.items().isEmpty() || current.polledAt().plus(STALE_AFTER).isBefore(Instant.now())) {
            refreshSafely();
            current = snapshot;
        }
        return current;
    }

    @Scheduled(initialDelay = 15_000, fixedDelay = 1_800_000)
    public void scheduledRefresh() {
        refreshSafely();
    }

    private synchronized void refreshSafely() {
        List<NewsItem> items = new ArrayList<>();
        List<String> warnings = new ArrayList<>();
        try {
            pollPublicBulletins(items);
        } catch (Exception ex) {
            warnings.add("OESC bulletin source: " + shortMessage(ex));
        }
        for (String newsroom : ESA_NEWSROOMS) {
            try {
                pollCodeNewsroom(newsroom, items);
            } catch (Exception ex) {
                warnings.add("ESA newsroom: " + shortMessage(ex));
            }
        }

        Map<String, NewsItem> unique = new LinkedHashMap<>();
        for (NewsItem item : items) unique.putIfAbsent(item.url(), item);
        List<NewsItem> sorted = new ArrayList<>(unique.values());
        sorted.sort((a, b) -> {
            if (a.sortDate() == null && b.sortDate() == null) return a.title().compareToIgnoreCase(b.title());
            if (a.sortDate() == null) return 1;
            if (b.sortDate() == null) return -1;
            int dateOrder = b.sortDate().compareTo(a.sortDate());
            return dateOrder != 0 ? dateOrder : a.title().compareToIgnoreCase(b.title());
        });

        if (!sorted.isEmpty() || snapshot.items().isEmpty()) {
            snapshot = new Snapshot(
                Instant.now(),
                List.copyOf(sorted),
                List.of("Electrical Safety Authority — public OESC bulletins", "Electrical Safety Authority — OESC/CEC code announcements"),
                warnings.isEmpty() ? "ok" : String.join(" | ", warnings),
                "Severity is generated by Electrical Workbench from the public title/summary and is not an official ESA/CSA severity rating. ESA states that only sample OESC bulletins are public; the complete 2024 OESC bulletin set is provided with the purchased Code/CSA OnDemand access."
            );
        }
    }

    private void pollPublicBulletins(List<NewsItem> items) throws Exception {
        Document doc = Jsoup.connect(ESA_BULLETINS)
            .userAgent("ElectricalWorkbench/1.0 (+Ontario electrical code news feed)")
            .timeout((int) HTTP_TIMEOUT.toMillis())
            .get();

        for (Element row : doc.select("tr")) {
            Elements cells = row.select("td");
            if (cells.size() < 2) continue;
            Element link = cells.get(0).selectFirst("a[href]");
            if (link == null) continue;
            String url = link.absUrl("href");
            if (url.isBlank() || !url.toLowerCase(Locale.ROOT).contains(".pdf")) continue;

            String title = clean(cells.get(1).text());
            if (title.isBlank()) title = clean(link.text()).replaceFirst("(?i)^download\\s*", "");

            BulletinMeta meta = bulletinMetaCache.get(url);
            if (meta == null) {
                meta = readBulletinMeta(url, title);
                bulletinMetaCache.put(url, meta);
            }
            Severity severity = classify("bulletin", title, meta.firstPageText());
            String summary = "Public OESC bulletin";
            if (!meta.rules().isBlank()) summary += " — " + meta.rules();
            summary += ". Open the official ESA PDF for the complete bulletin.";
            items.add(new NewsItem(
                stableId("bulletin", url),
                "OESC Bulletin",
                "Electrical Safety Authority",
                title,
                summary,
                url,
                meta.issueDate(),
                meta.dateLabel(),
                meta.bulletinNumber(),
                severity.label(),
                severity.color(),
                severity.reason(),
                false
            ));
        }
    }

    private BulletinMeta readBulletinMeta(String url, String fallbackTitle) {
        try {
            HttpRequest request = HttpRequest.newBuilder(URI.create(url))
                .timeout(HTTP_TIMEOUT)
                .header("User-Agent", "ElectricalWorkbench/1.0")
                .GET()
                .build();
            HttpResponse<byte[]> response = http.send(request, HttpResponse.BodyHandlers.ofByteArray());
            if (response.statusCode() < 200 || response.statusCode() > 299) throw new IOException("HTTP " + response.statusCode());
            try (PDDocument pdf = Loader.loadPDF(response.body())) {
                PDFTextStripper stripper = new PDFTextStripper();
                stripper.setStartPage(1);
                stripper.setEndPage(Math.min(2, pdf.getNumberOfPages()));
                String text = stripper.getText(pdf);
                Matcher dateMatch = ISSUE_DATE.matcher(text);
                LocalDate date = null;
                String dateLabel = "Date not published on listing";
                if (dateMatch.find()) {
                    try {
                        YearMonth ym = YearMonth.parse(dateMatch.group(1).trim(), MONTH_YEAR);
                        date = ym.atDay(1);
                        dateLabel = ym.format(MONTH_YEAR);
                    } catch (DateTimeParseException ignored) { }
                }
                Matcher numberMatch = BULLETIN_NO.matcher(text);
                String number = numberMatch.find() ? numberMatch.group(1).trim() : inferBulletinNumber(url);
                Matcher rulesMatch = RULES.matcher(text);
                String rules = rulesMatch.find() ? clean(rulesMatch.group(1)) : "";
                return new BulletinMeta(date, dateLabel, number, rules, text);
            }
        } catch (Exception ex) {
            return new BulletinMeta(null, "Date unavailable", inferBulletinNumber(url), "", fallbackTitle);
        }
    }

    private void pollCodeNewsroom(String url, List<NewsItem> items) throws Exception {
        Document doc = Jsoup.connect(url)
            .userAgent("ElectricalWorkbench/1.0 (+Ontario electrical code news feed)")
            .timeout((int) HTTP_TIMEOUT.toMillis())
            .get();

        for (Element heading : doc.select("h3")) {
            Element link = heading.selectFirst("a[href]");
            if (link == null) continue;
            String title = clean(link.text());
            if (title.isBlank()) continue;

            LocalDate date = null;
            String summary = "";
            Element cursor = heading.nextElementSibling();
            for (int i = 0; i < 4 && cursor != null; i++, cursor = cursor.nextElementSibling()) {
                String text = clean(cursor.text());
                if (text.isBlank()) continue;
                if (date == null) {
                    try {
                        date = LocalDate.parse(text, ESA_DATE);
                        continue;
                    } catch (DateTimeParseException ignored) { }
                }
                if (summary.isBlank()) summary = text;
            }

            String combined = (title + " " + summary).toLowerCase(Locale.ROOT);
            if (!isCodeRelated(combined)) continue;
            String articleUrl = link.absUrl("href");
            Severity severity = classify("code", title, summary);
            items.add(new NewsItem(
                stableId("code", articleUrl),
                "CEC/OESC Code Notice",
                "Electrical Safety Authority",
                title,
                summary.isBlank() ? "Official ESA code-related notice." : summary,
                articleUrl,
                date,
                date == null ? "Date unavailable" : date.format(ESA_DATE),
                "",
                severity.label(),
                severity.color(),
                severity.reason(),
                false
            ));
        }
    }

    private boolean isCodeRelated(String text) {
        return containsAny(text, Set.of(
            "ontario electrical safety code",
            "electrical safety code",
            "oesc",
            "canadian electrical code",
            "c22.1:24",
            "2024 code",
            "29th edition"
        ));
    }

    private Severity classify(String type, String title, String detail) {
        String text = (title + " " + detail).toLowerCase(Locale.ROOT);
        if (containsAny(text, Set.of(
            "serious electrical incident", "electrocution", "electrical shock", "shock hazard",
            "fire hazard", "unsafe", "energized equipment", "fatal", "dangerous", "rapid shutdown"
        ))) {
            return new Severity("URGENT", "#dc2626", "Public wording indicates an immediate electrical-safety hazard or serious-incident topic.");
        }
        if (containsAny(text, Set.of(
            "not compliant", "non-compliant", "approval", "requirements", "amendment", "effective",
            "high voltage", "energy storage", "grounding", "bonding", "protection", "service conductors",
            "working space", "gfci", "maximum circuit loading", "transfer equipment"
        ))) {
            return new Severity("IMPORTANT", "#d97706", "Likely to affect compliance, approval, protection or installation requirements.");
        }
        if ("bulletin".equals(type)) {
            return new Severity("TECHNICAL", "#2563eb", "OESC technical interpretation or application guidance.");
        }
        return new Severity("INFO", "#64748b", "General Code publication, availability or informational notice.");
    }

    private static boolean containsAny(String text, Set<String> terms) {
        for (String term : terms) if (text.contains(term)) return true;
        return false;
    }

    private static String inferBulletinNumber(String url) {
        String name = url.substring(url.lastIndexOf('/') + 1).replaceAll("(?i)\\.pdf.*$", "");
        Matcher m = Pattern.compile("0*([0-9]+)-0*([0-9]+)-0*([0-9]+)").matcher(name);
        return m.find() ? m.group(1) + "-" + m.group(2) + "-" + m.group(3) : "";
    }

    private static String stableId(String type, String value) {
        return type + "-" + Integer.toUnsignedString(value.hashCode(), 36);
    }

    private static String clean(String text) {
        return text == null ? "" : text.replace('\u00a0', ' ').replaceAll("\\s+", " ").trim();
    }

    private static String shortMessage(Exception ex) {
        String message = ex.getMessage();
        return message == null || message.isBlank() ? ex.getClass().getSimpleName() : message;
    }

    private record BulletinMeta(LocalDate issueDate, String dateLabel, String bulletinNumber, String rules, String firstPageText) { }
    private record Severity(String label, String color, String reason) { }

    public record NewsItem(
        String id,
        String type,
        String source,
        String title,
        String summary,
        String url,
        LocalDate sortDate,
        String dateLabel,
        String bulletinNumber,
        String severity,
        String severityColor,
        String severityReason,
        boolean severityOfficial
    ) { }

    public record Snapshot(
        Instant polledAt,
        List<NewsItem> items,
        List<String> sources,
        String status,
        String disclaimer
    ) { }
}
